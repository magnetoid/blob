// The sheet below 768px is Base UI's dialog, so it comes from the overlay chunk
// (`components/overlays/SidebarSheetImpl.tsx`): the chat shell draws its sidebar at first
// paint, and a statically imported Sheet would put the overlay code in the first load.
// For the same reason there is no Tooltip here — see `SidebarMenuButton`.
const SidebarSheet = lazyOverlay((m) => m.SidebarSheetImpl)

const SIDEBAR_WIDTH = "16rem"
const SIDEBAR_WIDTH_MOBILE = "18rem"
const SIDEBAR_WIDTH_ICON = "3rem"

type SidebarContextProps = {
  state: "expanded" | "collapsed"
  open: boolean
  setOpen: (open: boolean) => void
  openMobile: boolean
  setOpenMobile: (open: boolean) => void
  isMobile: boolean
  toggleSidebar: () => void
  /** The trigger that last opened the sheet, which is where focus goes when it closes. */
  openerRef: React.RefObject<HTMLElement | null>
}

const SidebarContext = React.createContext<SidebarContextProps | null>(null)

function useSidebar() {
  const context = React.useContext(SidebarContext)
  if (!context) {
    throw new Error("useSidebar must be used within a SidebarProvider.")
  }

  return context
}

function SidebarProvider({
  defaultOpen = true,
  open: openProp,
  onOpenChange: setOpenProp,
  className,
  style,
  children,
  ...props
}: React.ComponentProps<"div"> & {
  defaultOpen?: boolean
  open?: boolean
  onOpenChange?: (open: boolean) => void
}) {
  const isMobile = useIsMobile()
  const [openMobile, setOpenMobile] = React.useState(false)
  const openerRef = React.useRef<HTMLElement | null>(null)

  // This is the internal state of the sidebar.
  // We use openProp and setOpenProp for control from outside the component.
  const [_open, _setOpen] = React.useState(defaultOpen)
  const open = openProp ?? _open
  const setOpen = React.useCallback(
    (value: boolean | ((value: boolean) => boolean)) => {
      const openState = typeof value === "function" ? value(open) : value
      if (setOpenProp) {
        setOpenProp(openState)
      } else {
        _setOpen(openState)
      }
      // No `sidebar_state` cookie, which the generated component writes here: it would
      // ride on every request to the server for a preference only the client reads.
    },
    [setOpenProp, open]
  )

  // Helper to toggle the sidebar.
  const toggleSidebar = React.useCallback(() => {
    return isMobile ? setOpenMobile((open) => !open) : setOpen((open) => !open)
  }, [isMobile, setOpen, setOpenMobile])

  // And no ⌘B, the generated component's shortcut for this. Slack has no such key, so
  // nobody's fingers expect it, and every shortcut Blob answers is `lib/shortcuts`', where
  // the ⌘/ help lists it.

  // We add a state so that we can do data-state="expanded" or "collapsed".
  // This makes it easier to style the sidebar with Tailwind classes.
  const state = open ? "expanded" : "collapsed"

  const contextValue = React.useMemo<SidebarContextProps>(
    () => ({
      state,
      open,
      setOpen,
      isMobile,
      openMobile,
      setOpenMobile,
      toggleSidebar,
      openerRef,
    }),
    [state, open, setOpen, isMobile, openMobile, setOpenMobile, toggleSidebar]
  )

  return (
    <SidebarContext.Provider value={contextValue}>
      <div
        data-slot="sidebar-wrapper"
        style={
          {
            "--sidebar-width": SIDEBAR_WIDTH,
            "--sidebar-width-icon": SIDEBAR_WIDTH_ICON,
            ...style,
          } as React.CSSProperties
        }
        className={cn(
          "group/sidebar-wrapper flex min-h-svh w-full has-data-[variant=inset]:bg-sidebar",
          className
        )}
        {...props}
      >
        {children}
      </div>
    </SidebarContext.Provider>
  )
}

function Sidebar({
  side = "left",
  variant = "sidebar",
  collapsible = "offcanvas",
  label = "Sidebar",
  closeLabel = "Close",
  className,
  children,
  dir,
  ...props
}: React.ComponentProps<"div"> & {
  side?: "left" | "right"
  variant?: "sidebar" | "floating" | "inset"
  collapsible?: "offcanvas" | "icon" | "none"
  /** What the sheet is called below the breakpoint, where it is a dialog. */
  label?: string
  /** What the sheet's close button is called, for a screen reader that has no Escape. */
  closeLabel?: string
}) {
  const { isMobile, state, openMobile, setOpenMobile, openerRef } = useSidebar()

  // Mounted the first time the sheet opens, as every overlay is (`lazyOverlay`), and kept
  // after that, so Base UI can play its exit on every close. Kept only while the chunk is
  // here: one that failed to load drew nothing, and a wrapper left mounted through that
  // would try the import again on every render of the sidebar.
  const [sheetOpened, setSheetOpened] = React.useState(false)
  if (isMobile && openMobile && !sheetOpened) setSheetOpened(true)

  // The sheet's place on the Escape stack (`lib/useEscape.ts`), taken as it opens, as every
  // dialog's is. Base UI answers a key from inside the drawn sheet itself; until it is drawn
  // — the chunk still on its way — or for a key from outside it, the layer answers, so the
  // key never reaches what is underneath: a panel opened before it, or the shell's own
  // listener on `window`, which takes a stray Escape as "close the thread" or "mark this
  // channel read". One object for the sidebar's life: a new one would re-register the
  // layer on top.
  const popupRef = React.useRef<React.RefObject<HTMLElement | null> | null>(null)
  const onDrawn = React.useCallback((popup: React.RefObject<HTMLElement | null>) => {
    popupRef.current = popup
  }, [])
  const [standIn] = React.useState<StandIn>(() => ({
    drawn: () => popupRef.current?.current != null,
    holds: (target) =>
      target instanceof Node && (popupRef.current?.current?.contains(target) ?? false),
    close: () => setOpenMobile(false),
  }))
  useEscapeLayer(isMobile && openMobile && collapsible !== "none", standIn)

  if (collapsible === "none") {
    return (
      <div
        data-slot="sidebar"
        className={cn(
          "flex h-full w-(--sidebar-width) flex-col bg-sidebar text-sidebar-foreground",
          className
        )}
        {...props}
      >
        {children}
      </div>
    )
  }

  if (isMobile) {
    const drawn = openMobile || (sheetOpened && loadedOverlays() !== null)
    return drawn ? (
      <SidebarSheet
        open={openMobile}
        onOpenChange={setOpenMobile}
        side={side}
        dir={dir}
        width={SIDEBAR_WIDTH_MOBILE}
        label={label}
        closeLabel={closeLabel}
        openerRef={openerRef}
        onDrawn={onDrawn}
      >
        {children}
      </SidebarSheet>
    ) : null
  }

  return (
    <div
      className="group peer hidden text-sidebar-foreground md:block"
      data-state={state}
      data-collapsible={state === "collapsed" ? collapsible : ""}
      data-variant={variant}
      data-side={side}
      data-slot="sidebar"
    >
      {/* This is what handles the sidebar gap on desktop */}
      <div
        data-slot="sidebar-gap"
        className={cn(
          "relative w-(--sidebar-width) bg-transparent transition-[width] duration-200 ease-linear",
          "group-data-[collapsible=offcanvas]:w-0",
          "group-data-[side=right]:rotate-180",
          variant === "floating" || variant === "inset"
            ? "group-data-[collapsible=icon]:w-[calc(var(--sidebar-width-icon)+(--spacing(4)))]"
            : "group-data-[collapsible=icon]:w-(--sidebar-width-icon)"
        )}
      />
      <div
        data-slot="sidebar-container"
        data-side={side}
        className={cn(
          "fixed inset-y-0 z-10 hidden h-svh w-(--sidebar-width) transition-[left,right,width] duration-200 ease-linear data-[side=left]:left-0 data-[side=left]:group-data-[collapsible=offcanvas]:left-[calc(var(--sidebar-width)*-1)] data-[side=right]:right-0 data-[side=right]:group-data-[collapsible=offcanvas]:right-[calc(var(--sidebar-width)*-1)] md:flex",
          // Adjust the padding for floating and inset variants.
          variant === "floating" || variant === "inset"
            ? "p-2 group-data-[collapsible=icon]:w-[calc(var(--sidebar-width-icon)+(--spacing(4))+2px)]"
            : "group-data-[collapsible=icon]:w-(--sidebar-width-icon) group-data-[side=left]:border-r group-data-[side=right]:border-l",
          className
        )}
        {...props}
      >
        <div
          data-sidebar="sidebar"
          data-slot="sidebar-inner"
          className="flex size-full flex-col bg-sidebar group-data-[variant=floating]:rounded-lg group-data-[variant=floating]:shadow-sm group-data-[variant=floating]:ring-1 group-data-[variant=floating]:ring-sidebar-border"
        >
          {children}
        </div>
      </div>
    </div>
  )
}

function SidebarTrigger({
  className,
  onClick,
  ...props
}: React.ComponentProps<typeof Button>) {
  const { toggleSidebar, openerRef } = useSidebar()

  return (
    <Button
      data-sidebar="trigger"
      data-slot="sidebar-trigger"
      variant="ghost"
      size="icon-sm"
      className={cn(className)}
      onClick={(event) => {
        onClick?.(event)
        openerRef.current = event.currentTarget
        toggleSidebar()
      }}
      {...props}
    >
      <PanelLeftIcon />
      <span className="sr-only">Toggle Sidebar</span>
    </Button>
  )
}

